-- PostgreSQL schema for PROJECT_2_2.
-- Run only against the NEW project_2_postgres database.
-- Then run import_csv_data.py to load the five supplied CSV files.

CREATE TABLE IF NOT EXISTS students (
    student_id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(50),
    section VARCHAR(50),
    branch VARCHAR(100),
    current_year INTEGER,
    current_semester INTEGER,
    academic_year INTEGER
);

CREATE TABLE IF NOT EXISTS user_accounts (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(20) REFERENCES students(student_id) ON DELETE SET NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'student',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS curriculum (
    subject_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR(100) NOT NULL,
    subject_name VARCHAR(255) NOT NULL,
    branch VARCHAR(100) NOT NULL,
    academic_year INTEGER NOT NULL,
    semester INTEGER NOT NULL,
    credits NUMERIC(6,2),
    maximum_marks NUMERIC(7,2),
    UNIQUE (branch, academic_year, semester, subject_code)
);

CREATE TABLE IF NOT EXISTS academic_records (
    record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(20) NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    name VARCHAR(255),
    email VARCHAR(255),
    section VARCHAR(50),
    branch VARCHAR(100),
    academic_year INTEGER NOT NULL,
    semester INTEGER NOT NULL,
    subject_id INTEGER REFERENCES curriculum(subject_id) ON DELETE SET NULL,
    subject_code VARCHAR(100) NOT NULL,
    subject_name VARCHAR(255),
    credits NUMERIC(6,2),
    quiz1 NUMERIC(7,2),
    quiz2 NUMERIC(7,2),
    midsem NUMERIC(7,2),
    assignment NUMERIC(7,2),
    endsem NUMERIC(7,2),
    classes_attended INTEGER,
    classes_held INTEGER,
    attendance_percentage NUMERIC(6,2),
    marks_obtained NUMERIC(7,2),
    maximum_marks NUMERIC(7,2),
    grade VARCHAR(10),
    grade_point NUMERIC(5,2),
    backlog INTEGER NOT NULL DEFAULT 0,
    UNIQUE (student_id, academic_year, semester, subject_code)
);

CREATE TABLE IF NOT EXISTS semester_results (
    semester_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(20) NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    academic_year INTEGER NOT NULL,
    semester INTEGER NOT NULL,
    semester_percentage NUMERIC(6,2),
    sga NUMERIC(5,2),
    total_backlogs INTEGER NOT NULL DEFAULT 0,
    total_credits NUMERIC(7,2),
    semester_status VARCHAR(100),
    result_type VARCHAR(30) NOT NULL DEFAULT 'Actual',
    UNIQUE (student_id, academic_year, semester, result_type)
);

CREATE TABLE IF NOT EXISTS predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(20) NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    subject_id INTEGER REFERENCES curriculum(subject_id) ON DELETE SET NULL,
    prediction_type VARCHAR(100),
    predicted_marks NUMERIC(7,2),
    predicted_grade VARCHAR(10),
    lower_bound NUMERIC(7,2),
    upper_bound NUMERIC(7,2),
    prediction_confidence NUMERIC(7,4),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS prediction_feedback (
    feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id BIGINT NOT NULL REFERENCES predictions(prediction_id) ON DELETE CASCADE,
    actual_marks NUMERIC(7,2),
    actual_grade VARCHAR(10),
    absolute_error NUMERIC(7,2),
    feedback_notes TEXT,
    feedback_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS overall_prediction_history (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(20) NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    academic_year INTEGER NOT NULL,
    semester INTEGER NOT NULL,
    predicted_sga NUMERIC(5,2),
    estimated_cg NUMERIC(5,2),
    predicted_backlog_count INTEGER,
    backlog_risk VARCHAR(50),
    performance_category VARCHAR(100),
    overall_academic_risk VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS overall_prediction_subjects (
    overall_subject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id BIGINT NOT NULL REFERENCES overall_prediction_history(prediction_id) ON DELETE CASCADE,
    subject_code VARCHAR(100),
    subject_name VARCHAR(255),
    credits NUMERIC(6,2),
    predicted_marks NUMERIC(7,2),
    estimated_grade VARCHAR(10),
    attendance_percentage NUMERIC(6,2),
    backlog_risk VARCHAR(50),
    historical_average NUMERIC(7,2),
    performance_vs_history NUMERIC(7,2)
);

CREATE TABLE IF NOT EXISTS student_academic_submissions (
    submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(20) NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    student_name VARCHAR(255),
    branch VARCHAR(100),
    subject_code VARCHAR(100) NOT NULL,
    subject_name VARCHAR(255),
    academic_year INTEGER NOT NULL,
    semester INTEGER NOT NULL,
    quiz1 NUMERIC(7,2),
    quiz2 NUMERIC(7,2),
    midsem NUMERIC(7,2),
    assignment NUMERIC(7,2),
    classes_attended INTEGER,
    classes_held INTEGER,
    attendance_percentage NUMERIC(6,2),
    prev_sga NUMERIC(5,2),
    prev_sem_percentage NUMERIC(6,2),
    prev_total_backlogs INTEGER,
    status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    admin_notes TEXT,
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP,
    reviewed_by VARCHAR(255)
);

CREATE INDEX IF NOT EXISTS idx_academic_records_student_term
    ON academic_records(student_id, academic_year, semester);
CREATE INDEX IF NOT EXISTS idx_academic_records_subject_term
    ON academic_records(subject_code, academic_year, semester);
CREATE INDEX IF NOT EXISTS idx_semester_results_student_term
    ON semester_results(student_id, academic_year, semester);
CREATE INDEX IF NOT EXISTS idx_predictions_student_created
    ON predictions(student_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_feedback_prediction
    ON prediction_feedback(prediction_id);
CREATE INDEX IF NOT EXISTS idx_overall_history_student_term
    ON overall_prediction_history(student_id, academic_year, semester);
